"""
Data models for the Capsera SDK.

TokenEvent is the canonical unit of data produced by the interceptor and
shipped to the backend.  It is intentionally a plain dataclass so it is
easy to serialise, copy, and test without any heavy dependencies.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any


class BudgetExceededError(RuntimeError):
    """Raised when pre-call budget enforcement blocks an LLM request."""


# Backend ingest contract limits (backend/app/schemas/event.py). A field
# above its max poisons the whole batch, so TokenEvent truncates/floors at
# construction — see TokenEvent.__post_init__.
_CONTRACT_MAX_LEN = {
    "model": 64,
    "provider": 64,
    "gateway": 64,
    "original_model": 64,
    "system_prompt_hash": 64,
    "agent_id": 128,
    "env": 128,
    "team_id": 128,
    "task_type": 128,
    "customer_id": 128,
    "cost_center": 128,
    "error_type": 128,
    "caller_file": 512,
}
_CONTRACT_NON_NEGATIVE = (
    "input_tokens",
    "output_tokens",
    "cache_read_tokens",
    "cache_write_tokens",
    "latency_ms",
    "system_prompt_tokens",
    "message_count",
    "conversation_tokens",
    "few_shot_pairs",
    "tool_result_tokens",
    "conversation_turns",
)


@dataclass
class TokenEvent:
    """
    Represents a single LLM API call with full attribution metadata.

    Fields map 1-to-1 with the TokenEvent TimescaleDB schema defined in
    CLAUDE.md so the backend can insert them without transformation.
    Construction normalizes every field into the ingest contract's range —
    see ``__post_init__``.
    """

    # Identity
    id: str                          # UUID, generated by interceptor
    timestamp: str                   # ISO-8601 UTC, e.g. "2026-04-19T12:00:00+00:00"
    request_id: str                  # Separate deduplication key (also UUID)

    # LLM call
    model: str                       # e.g. "claude-sonnet-4-6"
    provider: str                    # "anthropic" | "openai" | "google"

    # Token counts
    input_tokens: int
    output_tokens: int
    cache_read_tokens: int = 0       # Anthropic cache reads
    cache_write_tokens: int = 0      # Anthropic cache writes

    # Cost
    cost_usd: float = 0.0            # Computed at SDK side; confirmed by backend

    # Attribution (populated from context stack / config)
    agent_id: str = "unknown"
    env: str = "development"
    team_id: str | None = None
    task_type: str | None = None
    session_id: str | None = None
    user_id: str | None = None
    customer_id: str | None = None
    cost_center: str | None = None

    # Request metadata
    latency_ms: int = 0
    caller_file: str | None = None
    # AI gateway the call rode through, when one was detected or declared
    # ("litellm" | "portkey" | "openrouter" | "bifrost" | "helicone" | ...).
    # None for direct provider calls. Orthogonal to ``provider``.
    gateway: str | None = None

    # Routing
    was_routed: bool = False
    original_model: str | None = None

    # Error capture — set when the provider call raised instead of returning.
    is_error: bool = False
    error_type: str | None = None

    # Prompt analysis (opt-in)
    system_prompt_hash: str | None = None
    system_prompt_tokens: int = 0
    message_count: int = 0
    conversation_tokens: int = 0
    has_few_shot: bool = False
    few_shot_pairs: int = 0
    tool_result_tokens: int = 0
    conversation_turns: int = 0
    context_window_utilization: float = 0.0

    # ------------------------------------------------------------------ #
    # Contract normalization
    # ------------------------------------------------------------------ #
    # The backend parses the WHOLE ingest batch as one Pydantic model
    # (EventBatch → EventIn), so a single out-of-contract field 422s every
    # event in the flush; the emitter retries the identical payload and then
    # drops all of it. Provider responses and tag()/record() arguments are
    # untrusted, so events normalize themselves at construction — string
    # fields truncate to the contract's maxima, counters floor at zero, and
    # the context-window ratio caps into [0, 1] (an over-window prompt
    # genuinely estimates above 1.0). Limits mirror
    # backend/app/schemas/event.py; the validation suite asserts the two
    # stay in lockstep.

    def __post_init__(self) -> None:
        for name, limit in _CONTRACT_MAX_LEN.items():
            value = getattr(self, name)
            if isinstance(value, str) and len(value) > limit:
                setattr(self, name, value[:limit])
        for name in _CONTRACT_NON_NEGATIVE:
            value = getattr(self, name)
            if isinstance(value, (int, float)) and value < 0:
                setattr(self, name, 0)
        if self.cost_usd < 0:
            self.cost_usd = 0.0
        if self.context_window_utilization < 0.0:
            self.context_window_utilization = 0.0
        elif self.context_window_utilization > 1.0:
            self.context_window_utilization = 1.0

    # ------------------------------------------------------------------ #
    # Serialisation helpers
    # ------------------------------------------------------------------ #

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable dict, dropping None values."""
        result: dict[str, Any] = {}
        for key, value in self.__dict__.items():
            if value is not None:
                result[key] = value
        return result


@dataclass
class PromptMetadata:
    """Structural metadata extracted from a prompt — never contains content."""

    system_prompt_hash: str | None = None
    system_prompt_tokens: int = 0
    message_count: int = 0
    conversation_tokens: int = 0
    has_few_shot: bool = False
    few_shot_pairs: int = 0
    tool_result_tokens: int = 0
    conversation_turns: int = 0
    context_window_utilization: float = 0.0


@dataclass
class RoutingDecision:
    """Result of evaluating routing rules against an LLM call."""

    routed: bool = False
    target_model: str | None = None
    original_model: str | None = None
    rule_name: str | None = None
    rule_type: str | None = None
